export const ATTRIBUTE_METADATA: { [K in CompareAttributeKey]: { label: string } } = {
  classe: { label: 'Classe' },
  habitat: { label: 'Habitat' },
  dieta: { label: 'Dieta' },
  tamanho: { label: 'Porte' },
  habito: { label: 'Hábito' },
  locomocao: { label: 'Locomoção' },
  continente: { label: 'Continente' },
  cobertura: { label: 'Revestimento' },
};

const SIZE_SCALE = {
  Pequeno: 0,
  Médio: 1,
  Grande: 2,
  Gigante: 3,
};

// Avaliação de correspondência exata ou proximidade (quase certo)
function evaluateAttribute(key: CompareAttributeKey, guessVal: string, secretVal: string): { status: MatchStatus; label: string } {
  if (guessVal === secretVal) {
    return { status: 'exact', label: 'Correto' };
  }

  // Regras de "Quase Certo" (Laranja)
  if (key === 'tamanho') {
    const d = Math.abs((SIZE_SCALE as any)[guessVal] - (SIZE_SCALE as any)[secretVal]);
    if (d === 1) {
      return { status: 'close', label: 'Porte próximo' };
    }
  }

  if (key === 'dieta') {
    const isShared =
      (guessVal === 'Carnívoro' && secretVal === 'Insetívoro') ||
      (guessVal === 'Insetívoro' && secretVal === 'Carnívoro') ||
      (guessVal === 'Onívoro' && (secretVal === 'Carnívoro' || secretVal === 'Herbívoro')) ||
      ((guessVal === 'Carnívoro' || guessVal === 'Herbívoro') && secretVal === 'Onívoro');
    if (isShared) {
      return { status: 'close', label: 'Dieta correlata' };
    }
  }

  if (key === 'habito') {
    const isAdjacent =
      (guessVal === 'Crepuscular' && (secretVal === 'Diurno' || secretVal === 'Noturno')) ||
      ((guessVal === 'Diurno' || guessVal === 'Noturno') && secretVal === 'Crepuscular');
    if (isAdjacent) {
      return { status: 'close', label: 'Horário próximo' };
    }
  }

  if (key === 'habitat') {
    const closeHabitats =
      (guessVal === 'Floresta' && secretVal === 'Montanha') ||
      (guessVal === 'Montanha' && secretVal === 'Floresta') ||
      (guessVal === 'Savana' && secretVal === 'Deserto') ||
      (guessVal === 'Deserto' && secretVal === 'Savana') ||
      (guessVal === 'Aquático' && secretVal === 'Polar') ||
      (guessVal === 'Polar' && secretVal === 'Aquático');
    if (closeHabitats) {
      return { status: 'close', label: 'Bioma próximo' };
    }
  }

  if (key === 'locomocao') {
    if (
      (guessVal === 'Anda/Corre' && secretVal === 'Pula') ||
      (guessVal === 'Pula' && secretVal === 'Anda/Corre')
    ) {
      return { status: 'close', label: 'Terrestre ágil' };
    }
  }

  if (key === 'classe') {
    if (
      (guessVal === 'Réptil' && secretVal === 'Anfíbio') ||
      (guessVal === 'Anfíbio' && secretVal === 'Réptil') ||
      (guessVal === 'Mamífero' && secretVal === 'Ave') ||
      (guessVal === 'Ave' && secretVal === 'Mamífero')
    ) {
      return { status: 'close', label: 'Grupo correlato' };
    }
  }

  return { status: 'different', label: 'Diferente' };
}

export function compareAnimals(guess: Animal, secret: Animal): AttributeComparison[] {
  const keys: CompareAttributeKey[] = [
    'classe',
    'habitat',
    'dieta',
    'tamanho',
    'habito',
    'locomocao',
    'continente',
    'cobertura',
  ];

  return keys.map((key) => {
    const { status, label } = evaluateAttribute(key, guess[key], secret[key]);
    return {
      key,
      label: ATTRIBUTE_METADATA[key].label,
      secretValue: secret[key],
      guessValue: guess[key],
      status,
      statusLabel: label,
    };
  });
}

export function calculateScore(tentativa: number): number {
  if (tentativa === 1) return 1000;
  if (tentativa === 2) return 850;
  if (tentativa === 3) return 700;
  if (tentativa === 4) return 550;
  if (tentativa === 5) return 400;
  if (tentativa === 6) return 250;
  if (tentativa === 7) return 150;
  return 100;
}

export function getRandomAnimal(excludeId?: string): Animal {
  const candidates = excludeId
    ? ANIMALS_DATABASE.filter((a) => a.id !== excludeId)
    : ANIMALS_DATABASE;
  const randomIndex = Math.floor(Math.random() * candidates.length);
  return candidates[randomIndex];
}
